const PARSER = `import { tokenize } from "./tokens";

export function parse(input: string, strict: boolean): number {
  let total = 0;
  for (const token of tokenize(input)) {
    if (token.kind === "number") {
      total += Number(token.value);
    } else if (token.kind === "op" && strict) {
      if (token.value === "-" || token.value === "+") {
        total = total * 2;
      } else {
        throw new Error("unsupported operator");
      }
    } else if (!strict && token.value.length > 0) {
      continue;
    }
  }
  return total;
}
`;

const TOKENS = `export interface Token {
  kind: "number" | "op";
  value: string;
}

export function tokenize(input: string): Token[] {
  return input.split(" ").map((value) => ({ kind: /\\d/.test(value) ? "number" : "op", value }));
}
`;

