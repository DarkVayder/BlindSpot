import { defaultConfig, type BlindspotConfig } from "@blindspot/core";
import type { TrackedEntry } from "@blindspot/git";
import { describe, expect, it } from "vitest";
import { countNonBlankLines, isBinary, isGenerated } from "./content.js";
import { selectFiles, type ExclusionReason } from "./discovery.js";

function entry(path: string, overrides: Partial<TrackedEntry> = {}): TrackedEntry {
  return { path, kind: "file", oid: "a".repeat(40), size: 100, ...overrides };
}

function reasons(entries: TrackedEntry[], config: BlindspotConfig = defaultConfig()) {
  const { candidates, excluded } = selectFiles(entries, config);
  return {
    included: candidates.map((c) => c.path),
    excluded: Object.fromEntries(excluded.map((e) => [e.path, e.reason])) as Record<string, ExclusionReason>,
  };
}

describe("selectFiles", () => {
  it("applies kind, extension, default exclusion and size rules in a fixed order", () => {
    const result = reasons([
      entry("src/app.ts"),
      entry("src/.hidden/config.ts"),
      entry("README.md"),
      entry("link.ts", { kind: "symlink" }),
      entry("vendor/lib", { kind: "submodule", size: null }),
      entry("node_modules/pkg/index.js"),
      entry("packages/x/dist/out.js"),
      entry("public/app.min.js"),
      entry("api/schema.generated.ts"),
      entry("huge.ts", { size: 5_000_000 }),
    ]);
    expect(result.included).toEqual(["src/.hidden/config.ts", "src/app.ts"]);
    expect(result.excluded).toEqual({
      "README.md": "extension",
      "link.ts": "symlink",
      "vendor/lib": "submodule",
      "node_modules/pkg/index.js": "default_excluded",
      "packages/x/dist/out.js": "default_excluded",
      "public/app.min.js": "default_excluded",
      "api/schema.generated.ts": "default_excluded",
      "huge.ts": "too_large",
    });
  });

  it("applies user include and exclude globs", () => {
    const config = defaultConfig();
    config.include = ["src/**"];
    config.exclude = ["**/*.test.ts"];
    expect(
      reasons([entry("src/a.ts"), entry("src/a.test.ts"), entry("scripts/b.ts")], config).excluded,
    ).toEqual({
      "src/a.test.ts": "user_excluded",
      "scripts/b.ts": "not_included",
    });
  });

  it("can turn the default exclusions off", () => {
    const config = defaultConfig();
    config.useDefaultExcludes = false;
    expect(reasons([entry("build/tool.ts")], config).included).toEqual(["build/tool.ts"]);
  });

  it("rejects undecodable, duplicate and non-relative paths", () => {
    const result = reasons([
      entry("bad�name.ts"),
      entry("dup.ts"),
      entry("dup.ts", { oid: "b".repeat(40) }),
      entry("a/../b.ts"),
      entry("/abs.ts"),
    ]);
    expect(result.included).toEqual([]);
    expect(new Set(Object.values(result.excluded))).toEqual(new Set(["invalid_path"]));
  });
});

describe("content checks", () => {
  it("detects binary content by a NUL byte near the start", () => {
    expect(isBinary(Buffer.from("plain text"))).toBe(false);
    expect(isBinary(Buffer.from([0x41, 0x00, 0x42]))).toBe(true);
  });

  it("detects generated-file headers only in leading comments", () => {
    expect(isGenerated("// @generated by protoc\nexport const x = 1;")).toBe(true);
    expect(isGenerated("// Code generated by sqlc. DO NOT EDIT.\npackage db")).toBe(true);
    expect(isGenerated("// <auto-generated />\nclass X {}")).toBe(true);
    expect(isGenerated('const marker = "@generated";\n')).toBe(false);
    expect(isGenerated(`${"\n".repeat(20)}// @generated`)).toBe(false);
  });

  it("counts non-blank lines across line ending styles", () => {
    expect(countNonBlankLines("a\r\n\r\nb\n  \nc\rd")).toBe(4);
    expect(countNonBlankLines("")).toBe(0);
  });
});
