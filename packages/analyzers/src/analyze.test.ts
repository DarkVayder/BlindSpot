import { defaultConfig } from "@blindspot/core";
import { listTrackedFiles, openRepository } from "@blindspot/git";
import { describe, expect, it } from "vitest";
import { TestRepo } from "../../git/src/test/repo.js";
import { analyzeFiles, type AnalyzedFile } from "./analyze.js";

const T = 20_000;

async function run(r: TestRepo, configure: (c: ReturnType<typeof defaultConfig>) => void = () => undefined) {
  const config = defaultConfig();
  configure(config);
  const repo = await openRepository(r.root, T);
  return analyzeFiles(repo, await listTrackedFiles(repo, T), config);
}

function byPath(files: AnalyzedFile[]) {
  return Object.fromEntries(files.map((f) => [f.path, f]));
}

describe("analyzeFiles", () => {
  it("analyzes a small mixed repository end to end", async () => {
    const r = TestRepo.create();
    r.write(
      "src/a.ts",
      'import { b } from "./b.js";\nimport { u } from "./util";\nexport const a = () => (b ? u : 0);\n',
    );
    r.write("src/b.ts", 'import { u } from "./util/index.js";\nexport const b = u > 0;\n');
    r.write("src/util/index.ts", "export const u = 1;\n");
    r.write("src/main.ts", 'import { a } from "./a";\nimport React from "react";\nconsole.log(a, React);\n');
    r.write("scripts/tool.py", "def main():\n    return 1\n");
    r.write("src/gen.ts", "// @generated by a tool\nexport const g = 1;\n");
    r.write("src/blob.ts", "\u0000binary");
    r.write("node_modules/dep/index.js", "module.exports = 1;\n");
    r.write("docs/readme.md", "# docs\n");
    r.commit("initial", "2026-01-01T00:00:00Z");
    r.write("src/a.ts", "uncommitted change that must be ignored\n");

    const result = await run(r, (c) => {
      c.critical = ["src/util/**"];
      c.provenance.declaredPaths = ["src/b.ts"];
    });
    const files = byPath(result.files);

    expect(Object.keys(files)).toEqual([
      "scripts/tool.py",
      "src/a.ts",
      "src/b.ts",
      "src/main.ts",
      "src/util/index.ts",
    ]);
    expect(Object.fromEntries(result.excluded.map((e) => [e.path, e.reason]))).toEqual({
      "docs/readme.md": "extension",
      "node_modules/dep/index.js": "default_excluded",
      "src/blob.ts": "binary",
      "src/gen.ts": "generated",
    });

    expect(files["src/util/index.ts"]?.dependencies).toEqual({
      status: "observed",
      value: { transitiveFanIn: 3 },
    });
    expect(files["src/b.ts"]?.dependencies).toEqual({ status: "observed", value: { transitiveFanIn: 2 } });
    expect(files["src/main.ts"]?.dependencies).toEqual({ status: "observed", value: { transitiveFanIn: 0 } });
    expect(result.importEdges).toBe(4);

    expect(files["src/a.ts"]?.complexity).toEqual({
      status: "observed",
      value: { cyclomaticMax: 2, cognitiveTotal: 1, codeLines: 3 },
    });
    expect(files["src/a.ts"]?.lineCount).toBe(3);

    expect(files["scripts/tool.py"]).toMatchObject({
      language: "python",
      lineCount: 2,
      complexity: { status: "missing", reason: "language_not_supported" },
      dependencies: { status: "missing", reason: "language_not_supported" },
    });

    expect(files["src/util/index.ts"]?.criticality).toEqual({
      status: "observed",
      value: { critical: true },
    });
    expect(files["src/a.ts"]?.criticality).toEqual({ status: "observed", value: { critical: false } });
    expect(files["src/b.ts"]?.declaredProvenance).toBe(true);
    expect(files["src/a.ts"]?.declaredProvenance).toBe(false);
    expect(result.warnings).toEqual([]);
  });

  it("reports criticality as not configured when no critical globs are set", async () => {
    const r = TestRepo.create();
    r.write("a.ts", "export const a = 1;\n").commit("one", "2026-01-01T00:00:00Z");
    const result = await run(r);
    expect(result.files[0]?.criticality).toEqual({ status: "missing", reason: "not_configured" });
  });

  it("analyzes identical content at two paths independently", async () => {
    const r = TestRepo.create();
    r.write("a.ts", "export const x = 1;\n")
      .write("copy/a.ts", "export const x = 1;\n")
      .commit("one", "2026-01-01T00:00:00Z");
    expect((await run(r)).files.map((f) => f.path)).toEqual(["a.ts", "copy/a.ts"]);
  });

  it("survives pathologically nested source without crashing the analysis", async () => {
    const r = TestRepo.create();
    const depth = 20_000;
    r.write("deep.ts", `export const x = ${"(".repeat(depth)}1${")".repeat(depth)};\n`);
    r.write("ok.ts", "export const y = 1;\n");
    r.commit("deep", "2026-01-01T00:00:00Z");
    const files = byPath((await run(r)).files);
    expect(files["ok.ts"]?.complexity.status).toBe("observed");
    expect(files["deep.ts"]).toMatchObject({
      lineCount: 1,
      complexity: { status: "missing", reason: "parse_failed" },
      dependencies: { status: "missing", reason: "parse_failed" },
    });
  });

  it("returns empty results for an empty repository", async () => {
    const r = TestRepo.create();
    await expect(run(r)).resolves.toEqual({
      files: [],
      excluded: [],
      importEdges: 0,
      graphComplete: true,
      warnings: [],
    });
  });
});
